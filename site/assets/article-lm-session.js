import { createInferenceRun } from "./model-topology.js";

export class ArticleLMSession {
  constructor(root, controller) {
    this.root = root;
    this.controller = controller;
    controller.lmSession = this;
    this.worker = new Worker(new URL("./model-lm-worker.js", import.meta.url), { type: "module" });
    this.id = 0;
    this.ready = false;
    this.pending = new Map();
    this.worker.onmessage = (event) => this.receive(event.data);
    this.worker.onerror = () => this.fail("The language-model worker could not start.");
    this.form = controller.form;
    this.submit = this.form.querySelector("button[type=submit]");
    this.submit.textContent = "Generate";
    this.submit.disabled = true;
    controller.input.disabled = true;
    const settings = document.createElement("div");
    settings.className = "machine-generation-settings";
    settings.innerHTML =
      '<label>New bytes<input type="number" min="1" max="128" value="32" data-lm-count></label><label>Temperature<input type="number" min="0" max="2" step="0.1" value="0.8" data-lm-temperature></label><label>Seed<input type="number" min="0" max="4294967295" value="17" data-lm-seed></label><button type="button" data-lm-stop disabled>Stop generation</button><p data-lm-status role="status">Loading trained model…</p>';
    this.settings = settings;
    this.backendStatus=document.createElement('p');this.backendStatus.dataset.lmBackendStatus='';this.backendStatus.className='machine-glass-note';
    this.backendStatus.textContent='Selecting inference backend…';settings.append(this.backendStatus);
    root.querySelector(".machine-settings-content").prepend(settings);
    this.status = settings.querySelector("[data-lm-status]");
    this.form.append(this.status);
    this.status.className = "machine-glass-note";
    this.stop = settings.querySelector("[data-lm-stop]");
    this.form.append(this.stop);
    this.stop.addEventListener("click", () => this.cancel());
    settings.append(controller.tokenReadout);
    const disclosure = root.querySelector(".machine-disclosure");
    if (disclosure)
      disclosure.textContent =
        "This viewer runs the trained unit-hypersphere research byte LM locally. Every inspected observation is a recorded intermediate tensor from the displayed generation. Displayed brightness and point size smoothly transition between observations; brightness is normalized per layer. Coordinate inspection shows signed raw values. Attention operator nodes show head-context RMS. Dense links remain visual bundles, not individual weight measurements.";
    if (disclosure) {
      const link = document.createElement("a");
      link.href = "/assets/lm/manifest.json";
      link.textContent = "Trained model provenance";
      disclosure.append(" ", link);
    }
    root.querySelector(".machine-console-label").textContent = "Generated continuation";
    root.querySelector('[data-glass-panel="input"] h3').textContent = "Generate locally.";
    root.querySelector('[data-glass-panel="output"] h3').textContent = "Generated bytes.";
    root.querySelector('[data-glass-panel="output"] .machine-glass-note').textContent = "Trained research baseline · 128 training steps · next-byte probabilities";
    const probabilities = document.createElement("p");
    probabilities.dataset.lmProbabilities = "";
    probabilities.className = "machine-glass-note";
    root.querySelector('[data-glass-panel="output"]').append(probabilities);
    if (disclosure) disclosure.append(" Runs locally in your browser. Your prompt is not sent to a server. Generation length, temperature, seed and input bytes are available in Settings.");
    root.addEventListener("portfolio:model-visibility", (event) => {
      if (!event.detail.visible) this.cancel();
    });
    addEventListener("pagehide", (event) => {
      if (!event.persisted) {
        this.cancel();
        this.worker.terminate();
      }
    });
    this.prepared = new Promise((resolve, reject) => {
      this.pending.set(++this.id, { resolve, reject });
      this.worker.postMessage({ type: "load", id: this.id });
    });
    this.prepared.catch(() => {});
  }
  receive(message) {
    if(message.backend){this.backend=message.backend;this.root.dataset.lmBackend=message.backend.selected;this.backendStatus.textContent=`Inference: ${message.backend.selected} · automatically selected for supported operations, numerical agreement and measured speed.`;}
    if (message.type === "ready") {
      this.ready = true;
      this.manifest = message.manifest;
      this.root.dataset.lmState = "ready";
      this.submit.disabled = false;
      this.controller.input.disabled = false;
      this.status.textContent = `Trained research LM · seed ${message.manifest.seed} · ${message.manifest.trainingSteps} training steps · ${message.manifest.contextBytes}-byte context. Temperature 0 is greedy.`;
      this.pending.get(message.id)?.resolve(message.manifest);
      this.pending.delete(message.id);
      return;
    }
    if (message.type === "error") {
      if (message.id !== this.id && !this.pending.has(message.id)) return;
      this.pending.get(message.id)?.reject(new Error(message.message));
      this.pending.delete(message.id);
      this.fail(message.message);
      return;
    }
    if (message.id !== this.id) return;
    const run = this.controller.runData;
    if (message.type === "token") {
      this.acceptToken(message);
      return;
    } else if (message.type === "complete") {
      run.generating = false;
      this.stop.disabled = true;
      this.submit.disabled = false;
      this.root.dataset.lmState = "ready";
      this.status.textContent = `Generated ${message.emitted.length} bytes locally. Play or scrub the recorded activations; token, shared pass, raw coordinate, and output stay linked.`;
      this.controller.draw();
    }
  }
  acceptToken(message) {
    const run = this.controller.runData;
    const previous = message.emitted.slice(0, -1).map((x) => x.toString(16).padStart(2, "0"));
    run.observations.push(
      ...message.observations.map((item) => ({ ...item, token: message.token, emitted: item.layer === 7 ? message.emitted.map((x) => x.toString(16).padStart(2, "0")) : previous })),
    );
    this.status.textContent = `Generating byte ${message.token + 1} · inspecting actual tensors from ${message.contextBytes} context bytes`;
    if (this.following && run.observations.length === message.observations.length && !matchMedia("(prefers-reduced-motion:reduce)").matches && !matchMedia("(forced-colors:active)").matches)
      this.controller.play();
    else if (this.following && !this.controller.playing) this.controller.frame = run.observations.length - 1;
    this.controller.draw();
  }
  async generate(text) {
    if (!this.ready) {
      this.status.textContent = "The trained model is still loading.";
      return;
    }
    this.cancel();
    this.controller.pause();
    this.following = true;
    const count = Number(this.settings.querySelector("[data-lm-count]").value),
      temperature = Number(this.settings.querySelector("[data-lm-temperature]").value),
      seed = Number(this.settings.querySelector("[data-lm-seed]").value);
    if (!Number.isInteger(count) || count < 1 || count > 128 || !Number.isFinite(temperature) || temperature < 0 || temperature > 2 || !Number.isInteger(seed) || seed < 0 || seed > 4294967295) {
      this.status.textContent = "Use 1–128 new bytes, temperature 0–2, and an integer seed.";
      return;
    }
    this.controller.input.value = text;
    this.controller.runData = createInferenceRun(text);
    this.controller.runData.generating = true;
    this.controller.tokenReadout.replaceChildren();
    this.controller.frame = 0;
    this.root.dataset.lmState = "generating";
    this.submit.disabled = true;
    this.stop.disabled = false;
    this.status.textContent = "Running the trained LM in your browser…";
    this.controller.draw();
    this.worker.postMessage({ type: "generate", id: ++this.id, prompt: text, count, temperature, seed });
  }
  cancel() {
    if (!this.controller.runData.generating) return;
    this.worker.postMessage({ type: "cancel" });
    this.id++;
    this.controller.runData.generating = false;
    this.stop.disabled = true;
    this.submit.disabled = !this.ready;
    this.root.dataset.lmState = this.ready ? "ready" : "loading";
    this.controller.pause();
    this.status.textContent = "Generation stopped. Recorded activations remain available.";
  }
  fail(message) {
    this.controller.runData.generating = false;
    this.stop.disabled = true;
    this.root.dataset.lmState = "error";
    this.status.textContent = `Language model unavailable: ${message}`;
    this.submit.disabled = true;
    this.controller.pause();
  }
}
