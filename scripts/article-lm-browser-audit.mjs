async function openTrainedArticle(page, url, requests) {
  await page.goto(url, { waitUntil: "networkidle" });
  const root = page.locator(".article-model-machine");
  await expect(root).toHaveCount(1);
  assert.equal(await root.getAttribute("data-illustration-fixture"), null, "Production article never substitutes a renderer fixture");
  assert.equal(
    requests.some((x) => x.includes("/lm/unit-hypersphere.f32")),
    false,
    "Model download requires reader intent",
  );
  const heading = await root.locator(".machine-heading h2").textContent();
  await expect(root.locator("[name=prompt]")).toBeDisabled();
  await root.locator("[data-model-start]").click();
  await expect(root).toHaveAttribute("data-startup", /^(ready|fallback)$/, { timeout: 30000 });
  await expect(root).toHaveAttribute("data-lm-state", "ready", { timeout: 30000 });
  await expect(root.locator(".machine-heading h2"), "Starting preserves the article presentation").toHaveText(heading);
  for (const pane of ["input", "inspect", "output"]) assert.equal(await root.locator(`[data-glass-panel=${pane}]`).getAttribute("aria-hidden"), null);
  await expect(root.locator("[name=prompt]")).toBeEnabled();
  return root;
}

async function generate(root, count, temperature) {
  await root.getByRole("button", { name: "Input", exact: true }).click();
  await root.locator("[name=prompt]").fill("the model");
  await root.locator("[data-machine-settings] summary").click();
  await root.locator("[data-lm-count]").fill(String(count));
  await root.locator("[data-lm-temperature]").fill(String(temperature));
  await root.locator("[data-machine-settings] summary").click();
  await root.getByRole("button", { name: "Generate", exact: true }).click();
  await expect(root).toHaveAttribute("data-lm-state", "ready", { timeout: 30000 });
}

async function verifyGeneration(root, page, config, view) {
  const { model, manifest, expected, out } = config;
  await generate(root, 4, 0);
  const observed = await root.evaluate((node) => ({ manifest: node.lmSession.manifest, records: node.machineController.runData.observations }));
  assert.equal(observed.manifest.sha256, manifest.sha256, "Rendered site uses the verified trained tensors");
  assert.equal(observed.records.length, 88, "Each generated byte records all three shared passes and its logits");
  assert.deepEqual(
    observed.records.at(-1).emitted.map((x) => parseInt(x, 16)),
    expected,
    "Actual worker generation matches the verified forward pass",
  );
  for (const item of observed.records) {
    assert.equal(item.values.length, [128, 384, 4, 128, 512, 128, 128, 256][item.layer]);
    assert.ok(item.values.every(Number.isFinite));
  }
  await root.locator("[data-machine-stage]").focus();
  await page.keyboard.press("End");
  await expect(root.locator("[data-machine-output]")).toHaveText(new TextDecoder().decode(new Uint8Array(expected)));
  await expect(root.locator("[data-lm-probabilities]")).toContainText("Top model probabilities");
  // Exercise sampled, visible continuation as well as the greedy oracle.
  const sampled = [],
    sampleInput = Array.from(new TextEncoder().encode("the model")),
    random = seededRandom(17);
  for (let i = 0; i < 8; i++) {
    const byte = sampleByte(forwardBytes(sampleInput, model).logits, 0.8, random);
    sampled.push(byte);
    sampleInput.push(byte);
  }
  await generate(root, 8, 0.8);
  await root.locator("[data-machine-stage]").focus();
  await page.keyboard.press("End");
  assert.deepEqual(await root.evaluate((node) => node.machineController.runData.observations.at(-1).emitted.map((x) => parseInt(x, 16))), sampled);
  await root.getByRole("button", { name: "Output", exact: true }).click();
  await root.locator("[data-machine-stage]").scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${out}/${view.name}-generation.png` });
  return { observed, sampled };
}

async function verifyFollowing(root, page) {
  await root.getByRole("button", { name: "Input", exact: true }).click();
  await expect(root.locator("[data-viewer-follow]")).toHaveAttribute("aria-pressed", "false");
  await expect(root.locator("[name=prompt]")).toBeEnabled();
  await root.getByRole("button", { name: "Coordinate", exact: true }).click();
  await expect(root.locator("[data-glass-panel=inspect]")).toHaveAttribute("data-context-focus", "true");
  await root.getByRole("button", { name: "Follow article", exact: true }).click();
  const headings = page.locator(".myst-reader [data-model-context]:not(.article-model-machine [data-model-context])");
  const contexts = await headings.evaluateAll((nodes) => nodes.map((node) => ({ id: node.id, part: node.dataset.modelContext, text: node.textContent.trim() })));
  assert.ok(contexts.length >= 3, "Assembled prose has context annotations");
  const varied = contexts.filter((item, index) => contexts.findIndex((x) => x.part === item.part) === index);
  assert.ok(varied.length >= 3, "Article follows distinct subsystems, not a constant default");
  for (const target of varied.filter((x) => x.id !== "accessible-used-question")) {
    await page.evaluate((id) => {
      const model = document.querySelector(".article-model-machine"),
        host = model.querySelector(".machine-spatial-host"),
        stage = model.querySelector("[data-machine-stage]");
      const header = document.querySelector(".topbar").getBoundingClientRect().height,
        toolbar = model.querySelector(".article-model-toolbar").getBoundingClientRect().height;
      const spatial = host?.dataset.instruments === "spatial" || model.dataset.modelReaderLayout === "true",
        height = (spatial ? host : stage).getBoundingClientRect().height;
      const line = Math.min(innerHeight - 3, header + toolbar + 12 + height + (spatial ? 28 : 72));
      scrollBy(0, document.getElementById(id).getBoundingClientRect().top - line + 2);
    }, target.id);
    await expect(root).toHaveAttribute("data-article-heading", target.id);
    await expect(root).toHaveAttribute("data-article-context", target.part);
    await expect(root.locator("[data-viewer-context]")).toContainText(target.text);
    await expect(root.locator(`[data-glass-panel=${modelContext(target.part).instrument}]`)).toHaveAttribute("data-context-focus", "true");
    assert.equal(await root.evaluate((node) => node.machineController.scene.focus), target.part);
    assert.equal(await root.evaluate((node) => node.machineController.scene.contextPart), target.part);
    await expect(root.locator(`[data-glass-panel=${modelContext(target.part).instrument}]`)).toBeVisible();
    assert.equal(await root.locator(".machine-spatial-host").evaluate((n) => getComputedStyle(n).position), "sticky", "The focused pane stays with the model while reading");
  }
  await root.locator("[data-machine-settings] summary").click();
  await root.getByRole("button", { name: "Zoom in", exact: true }).click();
  const chosen = await root.evaluate((node) => node.machine.diagnostics().camera);
  await expect(root.locator("[data-viewer-follow]")).toHaveAttribute("aria-pressed", "false");
  await headings.last().scrollIntoViewIfNeeded();
  assert.deepEqual(await root.evaluate((node) => node.machine.diagnostics().camera), chosen, "Reading preserves manual camera inspection");
  await root.locator("[data-machine-settings] summary").click();
  return contexts;
}

async function verifyPresentation(root, page) {
  await root.getByRole("button", { name: "Unpin model", exact: true }).click();
  await expect(root).toHaveAttribute("data-viewer-pinned", "false");
  assert.equal(await root.locator("[data-machine-stage]").evaluate((node) => getComputedStyle(node).position), "relative");
  await root.getByRole("button", { name: "Hide model", exact: true }).click();
  await expect(root.locator("[data-machine-stage]")).toBeHidden();
  await expect(root.getByRole("button", { name: "Show model", exact: true })).toBeVisible();
  assert.equal(await root.evaluate((node) => node.machine.clock().scheduled), false, "Hiding stops the animation clock");
  await page.reload({ waitUntil: "networkidle" });
  await expect(root).toHaveAttribute("data-viewer-hidden", "true");
  await expect(root).toHaveAttribute("data-viewer-pinned", "false");
  await root.getByRole("button", { name: "Show model", exact: true }).click();
  await expect(root.locator("[data-machine-stage]")).toBeVisible();
  await root.locator("[data-machine-stage]").scrollIntoViewIfNeeded();
}

async function auditProfile(browser, config, view) {
  const { base, article, manifest, expected, out } = config;
  const context = await browser.newContext({
    viewport: { width: view.width, height: view.height },
    deviceScaleFactor: view.dpr,
    colorScheme: "dark",
    isMobile: view.name === "phone",
    hasTouch: view.name === "phone",
  });
  const page = await context.newPage(),
    errors = [],
    requests = [],
    payloads = new Map(),
    payloadTasks = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("request", (request) => requests.push(request.url()));
  context.on("response", (response) =>
    payloadTasks.push(
      (async () => {
        const encoded = Number(response.headers()["content-length"] || 0);
        const bytes = encoded || (await response.body()).length;
        payloads.set(response.url(), Math.max(payloads.get(response.url()) || 0, bytes));
      })().catch(() => {}),
    ),
  );
  try {
    const root = await openTrainedArticle(page, base + article.url, requests);
    const { observed, sampled } = await verifyGeneration(root, page, config, view);
    const pose = await root.evaluate((node) => node.machine.diagnostics().camera);
    const contexts = await verifyFollowing(root, page);
    await verifyPresentation(root, page);
    const overflow = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }));
    assert.ok(overflow.scrollWidth <= overflow.width + 1, JSON.stringify(overflow));
    const axe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
    assert.deepEqual(
      axe.violations.map((x) => ({ id: x.id, targets: x.nodes.map((n) => n.target) })),
      [],
    );
    await page.screenshot({ path: `${out}/${view.name}.png` });
    // Worker downloads and session restoration are outside the final
    // document's Resource Timing list. Count unique observed payloads from
    // the entire activation, including its verified trained tensor bytes.
    await Promise.all(payloadTasks);
    const weightsURL = base + "/assets/lm/unit-hypersphere.f32";
    payloads.set(weightsURL, Math.max(payloads.get(weightsURL) || 0, manifest.bytes));
    const resources = [...payloads].map(([name, bytes]) => ({ name, bytes }));
    const total = resources.reduce((sum, x) => sum + x.bytes, 0);
    assert.ok(total <= 10_000_000, `Activated article exceeds 10 MB: ${total}`);
    assert.deepEqual(errors, []);
    return {
      profile: view,
      article: article.url,
      trainedState: manifest.trainedStateSha256,
      generatedBytes: expected,
      observations: observed.records.length,
      contexts,
      initialCamera: pose,
      bytes: total,
      resources,
      errors,
      sampledBytes: sampled,
    };
  } finally {
    await context.close();
  }
}

async function auditFallback(browser, config, mode) {
  const { base, article, expected } = config;
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: mode === "reduced-motion" ? "reduce" : "no-preference" }),
    page = await context.newPage();
  const engines = [];
  page.on("request", (request) => {
    if (request.url().includes("three@")) engines.push(request.url());
  });
  if (mode === "engine-unavailable") await page.route("**/vendor/three@*/**", (route) => route.abort());
  await page.goto(base + article.url, { waitUntil: "networkidle" });
  const root = page.locator(".article-model-machine");
  await root.locator(mode === "reduced-motion" ? "[data-model-quiet-load]" : "[data-model-start]").click();
  await expect(root).toHaveAttribute("data-lm-state", "ready", { timeout: 30000 });
  await generate(root, 4, 0);
  await root.locator("[data-machine-stage]").focus();
  await page.keyboard.press("End");
  assert.deepEqual(await root.evaluate((node) => node.machineController.runData.observations.at(-1).emitted.map((x) => parseInt(x, 16))), expected);
  await expect(root).toHaveAttribute("data-render", "fallback");
  if (mode === "reduced-motion") assert.deepEqual(engines, [], "Quiet inference never loads the WebGL engine");
  return { mode, generatedBytes: expected, engines };
}

export async function auditArticleLM() {
  const base = process.env.PORTFOLIO_AUDIT_URL || "http://127.0.0.1:4173";
  const response = await fetch(base + "/publication.json");
  assert.ok(response.ok, "Trained article audit requires a rendered publication");
  const publication = await response.json();
  const article = publication.articles.find((x) => x.slug === "accessible-does-not-imply-used") || publication.articles.find((x) => x.modelFocus);
  assert.ok(article, "A real published article is required");
  const manifest = JSON.parse(await readFile("site/assets/lm/manifest.json", "utf8"));
  const bytes = await readFile("site/assets/lm/unit-hypersphere.f32");
  const model = decodeWeights(manifest, bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
  const expected = [],
    input = Array.from(new TextEncoder().encode("the model"));
  for (let i = 0; i < 4; i++) {
    const byte = sampleByte(forwardBytes(input, model).logits, 0, seededRandom(17));
    expected.push(byte);
    input.push(byte);
  }
  const out = "ux-screenshots/article-lm";
  await mkdir(out, { recursive: true });
  const browser = await chromium.launch(),
    evidence = [];
  const config = { base, article, manifest, model, expected, out };
  try {
    for (const view of [
      { name: "desktop", width: 1366, height: 900, dpr: 2 },
      { name: "phone", width: 390, height: 844, dpr: 3 },
    ])
      evidence.push(await auditProfile(browser, config, view));
    for (const mode of ["reduced-motion", "engine-unavailable"]) evidence.push(await auditFallback(browser, config, mode));
  } finally {
    await browser.close();
    await writeFile(`${out}/audit.json`, JSON.stringify(evidence, null, 2) + "\n");
  }
  console.log(
    "Real article LM: verified generation and tensor observations, stable input/inspection, hide/show, unpin, article following, desktop/phone accessibility, and activated 10 MB budget passed.",
  );
}
